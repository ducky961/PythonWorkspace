print(1 + 1) # 2, 덧셈
print(3 - 2) # 1, 뺄셈
print(5 * 2) # 10, 곱셈
print(6 / 3) # 2, 나눗셈

print(2 ** 3) # 2^3 = 8, 제곱
print(5 % 3) # 2, 나머지 구하기
print(10 % 3) # 1, 나머지 구하기
print(5 // 3) # 3, 몫 구하기
print(10 // 3) # 3, 몫 구하기

print(10 > 3) # True
print(4 >= 7) # False
print(10 < 3) # False
print(5 <= 5) # True

print(3 == 3) # True
print(4 == 2) # False
print(3 + 4 == 7) # True

# not 연산자
print(1 != 3) # True
print(not(1 != 3)) # false
# and 연산자
print((3 > 0) and (3 < 5)) # True
print((3 > 0) & (3 < 5)) # True
# or 연산자
print((3 > 0) or (3 > 5)) # True
print((3 > 0) | (3 > 5)) # True
# 응용
print(5 > 4 > 3) # True
print(5 > 4 > 7) # False